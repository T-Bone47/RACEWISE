def map_f1db_record(entity_type: str, record: dict) -> dict:
    """Map a single F1DB record to canonical field names."""
    mapping = F1DB_TO_CANONICAL.get(entity_type, {})
    result = {}
    for f1db_key, canonical_key in mapping.items():
        if f1db_key in record:
            result[canonical_key] = record[f1db_key]
    return result


def map_f1db_records(entity_type: str, records: list[dict]) -> list[dict]:
    """Map a list of F1DB records to canonical field names."""
    return [map_f1db_record(entity_type, record) for record in records]